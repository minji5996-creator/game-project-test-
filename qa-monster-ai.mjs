import assert from 'node:assert/strict';
import {createFieldMonsters} from './src/field-monsters.js';
let player={hp:96,mp:42,level:1,element:'earth'},hits=0,rewards=0;
const world={npcs:[],nav:{walkable:()=>true,findPath:(from,to)=>[{x:to.x,z:to.z}]}};
const system=createFieldMonsters(world,{getPlayer:()=>player,onDamage:()=>{hits++;return false;},onReward:()=>rewards++,onNotice:()=>{},onCast:()=>{}});
const actor={position:{x:-18,z:9}};
for(let i=0;i<65;i++)system.update(.05,actor,true);
assert.equal(system.mobs[0].mode,'windup');
actor.position.x=-16;
for(let i=0;i<13;i++)system.update(.05,actor,true);
assert.equal(hits,0,'Moving out of the warning must dodge the hit');
const snapshot=JSON.stringify(system.state);
system.update(20,actor,false);
assert.equal(JSON.stringify(system.state),snapshot,'Paused monsters must stay frozen');
actor.position={x:0,z:11};
for(let i=0;i<100;i++)system.update(.05,actor,true);
assert.equal(hits,0,'Safe zone prevents damage');
assert.ok(['idle','return'].includes(system.mobs[0].mode));
system.reset();actor.position={x:-18,z:9};
assert.equal(system.cast(actor,'earth'),true);
assert.equal(system.cast(actor,'earth'),false,'Cast cooldown prevents spamming');
assert.equal(player.mp,39);
system.update(.3,actor,true);
assert.equal(system.mobs[0].mode,'dead','Element weakness can defeat the jelly');
assert.equal(rewards,1);system.update(.3,actor,true);assert.equal(rewards,1,'Reward once per defeat');
console.log('PASS: dodge, safe zone, pause, cooldown, weakness, single reward.');
